-- 1. ПОИСК ПОЛЬЗОВАТЕЛЯ ПО EMAIL
-- Задача: Пользователь жалуется, что не может войти. Нужно найти его в базе.
SELECT id, name, email, status, created_at 
FROM users 
WHERE email = 'user@example.com';

-- 2. ПРОВЕРКА ПОСЛЕДНИХ ЗАКАЗОВ ПОЛЬЗОВАТЕЛЯ
-- Задача: Пользователь говорит "мой заказ не прошёл". Проверяем его историю.
SELECT o.id, o.status, o.amount, o.created_at 
FROM orders o
WHERE o.user_id = 12345
ORDER BY o.created_at DESC
LIMIT 10;

-- 3. ПОИСК ЗАКАЗОВ С ОШИБКАМИ (СТАТУС 'FAILED')
-- Задача: Разобрать массовую жалобу на сбои оплаты за сегодня.
SELECT id, user_id, amount, error_message, created_at 
FROM orders 
WHERE status = 'failed' 
  AND created_at >= CURRENT_DATE
ORDER BY created_at DESC;

-- 4. ПОДСЧЁТ ОШИБОК ПО ТИПАМ (АГРЕГАЦИЯ)
-- Задача: Понять, какая ошибка встречается чаще всего, чтобы передать разработчикам.
SELECT error_code, COUNT(*) as error_count 
FROM system_logs 
WHERE created_at >= CURRENT_DATE
GROUP BY error_code
ORDER BY error_count DESC;

-- 5. ПОИСК ПОЛЬЗОВАТЕЛЕЙ БЕЗ АКТИВНЫХ ПОДПИСОК (LEFT JOIN)
-- Задача: Найти пользователей, которые зарегистрировались, но не оформили подписку.
SELECT u.id, u.name, u.email 
FROM users u
LEFT JOIN subscriptions s ON u.id = s.user_id
WHERE s.id IS NULL;

-- 6. ПРОВЕРКА ДУБЛИКАТОВ (например, одинаковых email)
-- Задача: Найти технические сбои, из-за которых создались дубликаты аккаунтов.
SELECT email, COUNT(*) as duplicate_count 
FROM users 
GROUP BY email 
HAVING COUNT(*) > 1
ORDER BY duplicate_count DESC;

